library(testthat)
library(data.table)
source('R/utils/era_dates.R')

test_that('Excel serials, DMY and ISO share one calendar without an epoch shift', {
  x <- era_decode_legacy_dates(c('38550','17/7/2005','2005-07-17','38550.0'))
  expect_identical(as.character(x$date), rep('2005-07-17',4))
  expect_identical(as.character(era_decode_legacy_dates(39445)$date),'2007-12-29')
  expect_equal(as.numeric(as.Date(38550,origin='1970-01-01')-x$date[1]),25569)
})
test_that('typed dates and missing representations are preserved', {
  x <- as.Date(c('2005-07-17',NA,'2023-10-01'))
  expect_identical(era_decode_legacy_dates(x)$date,x)
  expect_true(all(is.na(era_decode_legacy_dates(c(NA,'',' NA ','Not in template','-9999'))$date)))
  expect_true(all(is.na(era_decode_legacy_dates(c(NA,NA))$date)))
  expect_identical(as.character(era_decode_legacy_dates(factor('17/07/2005'))$date),'2005-07-17')
})
test_that('invalid, partial and ambiguous dates retain source evidence', {
  raw <- c('30/02/2011','2011-02-30','2012-02-29','2011-02-29',
           '15/02/05','January','2011-02','2011-02-01 extra','60','38550.5')
  x <- era_decode_legacy_dates(raw)
  expect_identical(x$raw,raw)
  expect_equal(which(!is.na(x$date)),3L)
  expect_identical(x$status[5],'ambiguous_two_digit_year')
  expect_identical(x$status[1:2],rep('invalid_calendar_date',2))
  expect_identical(x$status[9],'unsupported_serial')
  expect_error(era_decode_legacy_dates(as.POSIXct('2005-07-17',tz='UTC')),'Unsupported')
})
test_that('unknown-year meaning is not invented', {
  x <- era_decode_legacy_dates(c('01/01/9999','99999.1'))
  expect_identical(as.character(x$date[1]),'9999-01-01')
  expect_identical(x$status[1],'unresolved_year')
  expect_true(is.na(x$date[2]))
})
test_that('binding fails before implicit character/numeric date coercion', {
  ie <- data.table(id='ie',date=as.Date('2019-12-21'),value=4)
  mh <- data.table(id='mh',date='38550',value=5)
  expect_error(era_bind_date_safe(ie,mh,'Data.Out'),'Calendar-date type mismatch')
  mh[,date:=era_decode_legacy_dates(date)$date]
  x <- era_bind_date_safe(ie,mh,'Data.Out')
  expect_identical(x$date,c(ie$date,mh$date))
  expect_identical(x$value,c(4,5))
  expect_identical(ie$date,as.Date('2019-12-21'))
  mh[,date:=38550]
  expect_error(era_bind_date_safe(ie,mh,'Data.Out'),'Calendar-date type mismatch')
})
test_that('JSON round-trip keeps both cohorts and missing date values', {
  ie <- data.table(id=c('ie1','ie2'),date=as.Date(c('2019-12-21',NA)))
  mh <- data.table(id=c('mh1','mh2'),date=era_decode_legacy_dates(c('38550','15/04/2011'))$date)
  merged <- era_bind_date_safe(ie,mh,'Data.Out')
  restored <- jsonlite::fromJSON(jsonlite::toJSON(merged,Date='ISO8601',dataframe='rows'))
  expect_identical(restored$date,as.character(merged$date))
  expect_identical(restored$id,merged$id)
})
test_that('existing typed early and unresolved years survive JSON unchanged', {
  x <- as.Date(c('0005-02-15','9999-01-01',NA))
  json <- jsonlite::toJSON(data.frame(date=x),Date='ISO8601',dataframe='rows')
  restored <- jsonlite::fromJSON(json)
  expect_identical(as.Date(restored$date,format='%Y-%m-%d'),x)
  expect_identical(era_decode_legacy_dates(x)$date,x)
})
test_that('Date JSON preserves calendar days while RData retains fractional dates', {
  ie <- data.table(date=as.Date('2010-06-27')+0.5)
  mh <- data.table(date=as.Date('0005-02-15'))
  x <- era_bind_date_safe(ie,mh,'PD.Out')
  expect_identical(x$date,c(ie$date,mh$date))
  restored <- jsonlite::fromJSON(jsonlite::toJSON(x,Date='ISO8601',dataframe='rows'))
  expect_identical(restored$date,era_date_iso(x$date))
})
